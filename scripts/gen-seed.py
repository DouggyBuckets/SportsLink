#!/usr/bin/env python3
"""Regenerates the reference-data seed migration from lib/sports.ts and
lib/locations.ts so the bundled copies and the database can't drift.

    python3 scripts/gen-seed.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "supabase/migrations/20260921124000_seed_reference.sql"


def q(text):
    return "'" + text.replace("'", "''") + "'"


def arr(items):
    return "array[" + ", ".join(q(i) for i in items) + "]::text[]"


def strings(src):
    return re.findall(r'"([^"]+)"', src)


sports = re.findall(r's\("([^"]+)", "([^"]+)", "([^"]+)", "([^"]+)", \[([^\]]*)\], (\d+)\)', (ROOT / "lib/sports.ts").read_text())
locations = re.findall(
    r'\{ id: "([^"]+)", name: "([^"]+)", area: "([^"]+)", address: "([^"]*)", lat: ([\d.-]+), lng: ([\d.-]+), indoor: (true|false), sports: \[([^\]]*)\] \}',
    (ROOT / "lib/locations.ts").read_text(),
)
assert sports and locations, "parsers found nothing - did the TS source format change?"

sport_rows = ",\n".join(
    f"  ({q(i)}, {q(name)}, {q(icon)}, {q(color)}, {arr(strings(formats))}, {cap}, {(n + 1) * 10})"
    for n, (i, name, icon, color, formats, cap) in enumerate(sports)
)
location_rows = ",\n".join(
    f"  ({q(i)}, {q(name)}, {q(area)}, {q(addr)}, {lat}, {lng}, {indoor}, {arr(strings(sp))})" for i, name, area, addr, lat, lng, indoor, sp in locations
)

# Rec Sports drop-in slots that seed the feed. Empty for MVP1: none of
# the drop-ins are soccer. Rows look like
#   ("soccer", "hadley", "5v5", "Gym", 3, 1140, 120, 20, "Rec Sports drop-in.")
# (day_of_week 0 = Sunday, start in minutes past midnight).
sessions = []
session_rows = ",\n".join(f"  ({q(a)}, {q(b)}, {q(c)}, {q(d)}, {e}, {f}, {g}, {h}, {q(i)})" for a, b, c, d, e, f, g, h, i in sessions)
session_sql = (
    f"""
-- Recurring Rec Sports drop-in slots that seed the feed (the cold-start fix).
-- Check times against recreation.umich.edu each semester.
insert into public.official_sessions (sport_id, location_id, format, location_note, day_of_week, start_min, duration_min, capacity, notes) values
{session_rows};
"""
    if sessions
    else "\n-- No Rec Sports drop-in sessions for MVP1 (soccer only).\n"
)

OUT.write_text(f"""-- Reference data. GENERATED by scripts/gen-seed.py from lib/sports.ts and
-- lib/locations.ts - edit those and re-run it rather than editing this file.

insert into public.sports (id, name, sf_symbol, color, formats, default_capacity, sort_order) values
{sport_rows}
on conflict (id) do update set name = excluded.name, sf_symbol = excluded.sf_symbol, color = excluded.color, formats = excluded.formats, default_capacity = excluded.default_capacity, sort_order = excluded.sort_order;

-- Venue list checked against Michigan Recreation for fall 2026 (Hadley Center
-- open, CCRB and the old Elbel Field gone). Coordinates are approximate - good
-- enough to open Maps in the right place. 'other' backs the free-text option.
insert into public.locations (id, name, area, address, lat, lng, indoor, sports) values
{location_rows}
on conflict (id) do update set name = excluded.name, area = excluded.area, address = excluded.address, lat = excluded.lat, lng = excluded.lng, indoor = excluded.indoor, sports = excluded.sports;

{session_sql}""")
print(f"wrote {OUT.relative_to(ROOT)}: {len(sports)} sports, {len(locations)} locations, {len(sessions)} sessions")
